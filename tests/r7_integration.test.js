const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),os=require('node:os');
const {createWorkspaceStore}=require('../src/main/store');
const {watchWorkspace}=require('../src/main/workspaceWatcher');
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
test('directory watcher reloads atomic state and layout saves and emits only a revision',async t=>{
 const root=fs.mkdtempSync(path.join(os.tmpdir(),'papercard-watch-'));
 t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
 const store=createWorkspaceStore(root),page=store.importPage({title:'one'});
 const card=store.addCard({pageId:page.pageId,title:'card'});
 const events=[],errors=[];const stop=watchWorkspace({store,notify:e=>events.push(e),debounceMs:15,onError:e=>errors.push(e)});t.after(stop);
 const wait=async count=>{for(let i=0;i<100&&events.length<count;i++)await sleep(10);assert.equal(events.length,count);};
 const external=createWorkspaceStore(root);external.renameBatch({batchId:page.batchId,title:'external'});
 await wait(1);assert.equal(store.getState().batches[0].title,'external');
 external.updateCanvasLayout([{cardId:card.cardId,x:321,y:456}]);
 await wait(2);assert.equal(store.getState().cards[0].x,321);
 assert.deepEqual(Object.keys(events[0]).sort(),['action','revision']);assert.ok(events[1].revision>events[0].revision);
 await sleep(50);assert.equal(events.length,2);assert.equal(errors.length,0);stop();
});
test('migration backs up state, overlay, pages and crops before externalizing; archive restores visuals and body',t=>{
 const root=fs.mkdtempSync(path.join(os.tmpdir(),'papercard-backup-'));t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
 const store=createWorkspaceStore(root),page=store.importPage({title:'original'});
 const svg='<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 20 30"><rect width="20" height="30" fill="blue"/></svg>';
 const body='用户正文 <svg> 不是图像';
 const card=store.addCard({pageId:page.pageId,title:'body',editableContent:body,figureInfo:{redrawSvg:svg}});
 store.updateCanvasLayout([{cardId:card.cardId,x:92,y:41}]);
 fs.mkdirSync(path.join(root,'pages'),{recursive:true});fs.writeFileSync(path.join(root,'pages','original.txt'),'page bytes');
 fs.mkdirSync(path.join(root,'crops'),{recursive:true});fs.writeFileSync(path.join(root,'crops','original.txt'),'crop bytes');
 const file=path.join(root,'workspace-state.json'),legacy=JSON.parse(fs.readFileSync(file));legacy.schemaVersion=6;legacy.pages[0].svgPreview=svg;delete legacy.pages[0].svgPreviewPath;
 fs.writeFileSync(file,JSON.stringify(legacy));const bytes=fs.readFileSync(file),overlay=fs.readFileSync(path.join(root,'workspace-layouts.json'));
 const migrated=createWorkspaceStore(root),backup=fs.readdirSync(path.join(root,'backups')).map(n=>path.join(root,'backups',n)).find(p=>fs.existsSync(path.join(p,'pages','original.txt')));
 assert.ok(backup);assert.deepEqual(fs.readFileSync(path.join(backup,'workspace-state.json')),bytes);assert.deepEqual(fs.readFileSync(path.join(backup,'workspace-layouts.json')),overlay);
 assert.equal(fs.readFileSync(path.join(backup,'crops','original.txt'),'utf8'),'crop bytes');assert.ok(fs.existsSync(path.join(backup,'backup-complete.json')));
 const current=migrated.getState();assert.equal(current.cards[0].editableContent,body);assert.equal(current.cards[0].x,92);
 const archived=migrated.archiveBatch({batchId:page.batchId});const data=JSON.parse(fs.readFileSync(archived.jsonPath));assert.ok(data.visualAssets.length>=1);
 const restored=migrated.restoreArchive({archiveId:archived.archiveId}),copy=migrated.getState().cards.find(c=>c.batchId===restored.batchId);
 assert.equal(copy.editableContent,body);assert.equal(fs.readFileSync(path.join(root,copy.figureInfo.redrawPath.slice(12)),'utf8'),svg);
 migrated.updateCard(copy.cardId,{figureInfo:{redrawPath:'data:image/png;base64,iVBORw0KGgo='}});
 assert.match(migrated.getState().cards.find(c=>c.cardId===copy.cardId).figureInfo.redrawPath,/^app:\/\/local\/crops\/visual-.*\.png$/);
});
